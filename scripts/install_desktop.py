#!/usr/bin/env python3
"""Устанавливает личный Linux-ярлык собранной игры, без sudo и изменения игрового профиля."""

import argparse
import os
from pathlib import Path
import shlex
import shutil
import subprocess
import sys

APP_ID = "org.alken1t15.BallAdventure"
MARKER = "# Generated by Ball Adventure desktop installer"


def entry_value(value):
    """Escaping строк Desktop Entry; это не shell quoting."""
    return str(value).replace("\\", "\\\\").replace(" ", "\\s").replace("\t", "\\t")


def exec_value(value):
    # String escaping применяется до Exec quoting; %% — буквальный процент.
    escaped = "".join("\\" + char if char in '\\"`$' else char for char in str(value))
    return '"' + escaped.replace("\\", "\\\\").replace("%", "%%") + '"'


def check_owned(path):
    if path.is_symlink() or (path.exists() and
                            (not path.is_file() or not path.read_text(encoding="utf-8").startswith(
                                (MARKER + "\n", "#!/bin/sh\n" + MARKER + "\n")))):
        raise ValueError(f"Не перезаписываю чужой файл: {path}")


def install(desktop=False):
    if not sys.platform.startswith("linux"):
        raise ValueError("Этот установщик предназначен для Linux; Windows описан в docs/desktop-launcher.md")
    root = Path(__file__).resolve().parent.parent
    assembly = root / "src/Platformer.App/bin/Release/net10.0/Platformer.App.dll"
    icon = root / "assets/branding/ball-adventure.png"
    play = root / "scripts/Play.sh"
    for source in (assembly, icon, play):
        if not source.is_file():
            raise ValueError(f"Нет {source}; сначала соберите игру по README")
    dotnet, bash = shutil.which("dotnet"), shutil.which("bash")
    if not dotnet or not bash or not shutil.which("setsid"):
        raise ValueError("Нужны dotnet (.NET 10 Runtime), bash и setsid (util-linux) в PATH")
    dotnet, bash = Path(dotnet).resolve(), Path(bash).resolve()
    data = Path(os.environ.get("XDG_DATA_HOME") or Path.home() / ".local/share").expanduser()
    if not data.is_absolute():
        raise ValueError("XDG_DATA_HOME должен быть абсолютным путём")
    applications = data / "applications"
    wrapper = data / "ball-adventure/launch.sh"
    destinations = [applications / f"{APP_ID}.desktop"]
    if desktop:
        tool = shutil.which("xdg-user-dir")
        if not tool:
            raise ValueError("Для --desktop нужен xdg-user-dir (пакет xdg-user-dirs)")
        result = subprocess.run([tool, "DESKTOP"], check=True, capture_output=True, text=True)
        directory = Path(result.stdout.strip())
        if not directory.is_absolute() or directory == Path.home():
            raise ValueError("Рабочий стол не настроен через xdg-user-dir DESKTOP")
        destinations.append(directory / "Ball Adventure.desktop")
    # Переводы строки в путях нельзя переносить в Desktop Entry или shell header.
    for path in (root, dotnet, bash, data, *destinations):
        if any(char in str(path) for char in "\r\n\t"):
            raise ValueError("Пути с переводами строк/табуляцией не поддерживаются")
    for path in (wrapper, *destinations):
        check_owned(path)
    wrapper_text = (f"#!/bin/sh\n{MARKER}\n"
                    f"export PATH={shlex.quote(str(dotnet.parent))}:\"$PATH\"\n"
                    f"exec {shlex.quote(str(bash))} {shlex.quote(str(play))} --visual\n")
    entry = (f"{MARKER}\n[Desktop Entry]\nType=Application\nName=Ball Adventure\n"
             "Comment=Roll, jump and explore floating islands\n"
             "Comment[ru]=Прыжки, монеты и приключение на воздушных островах\n"
             f"Exec=/bin/sh {exec_value(wrapper)}\nPath={entry_value(root)}\nIcon={entry_value(icon)}\n"
             "Terminal=false\nCategories=Game;ActionGame;\nStartupNotify=false\n")
    wrapper.parent.mkdir(parents=True, exist_ok=True)
    wrapper.write_text(wrapper_text, encoding="utf-8")
    wrapper.chmod(0o755)
    for destination in destinations:
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_text(entry, encoding="utf-8")
        destination.chmod(0o755 if destination.name == "Ball Adventure.desktop" else 0o644)
        print(f"Установлен ярлык: {destination}")
    print("Запуск из меню приложений: Ball Adventure (--visual). После переноса клона установите ярлык заново.")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--desktop", action="store_true", help="Также создать ярлык на рабочем столе XDG")
    args = parser.parse_args()
    try:
        install(args.desktop)
    except (ValueError, OSError, subprocess.SubprocessError) as error:
        print(f"Ball Adventure: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
